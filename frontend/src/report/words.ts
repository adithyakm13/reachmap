/** A fixed message for the status of a failed API call: never the body of the answer. */
export function errorWords(status: number): string {
  if (status === 0) return W.error0;
  if (status === 400) return W.error400;
  if (status === 401) return W.error401;
  if (status === 403) return W.error403;
  if (status === 404) return W.error404;
  if (status === 409) return W.error409;
  if (status === 413) return W.error413;
  if (status === 429) return W.error429;
  if (status >= 500) return W.error5xx;
  return W.errorOther;
}
